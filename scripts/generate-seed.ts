/**
 * Turns the built-in sample content into SQL for Supabase.
 * Usage: npm run seed:sql   (writes supabase/seed.sql)
 * Sample reviews are inserted as "hidden" so they never appear publicly.
 */
import { sample } from "../src/lib/sample-data";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const b = (v: boolean) => (v ? "true" : "false");
const tripId = (slug: string) => `(select id from public.trips where slug = ${q(slug)})`;
const destId = (slug: string) => `(select id from public.destinations where slug = ${q(slug)})`;

const out: string[] = [];
out.push("-- Generated by scripts/generate-seed.ts. Safe to run on an empty database.");
out.push("begin;");

for (const d of sample.destinations) {
  out.push(`insert into public.destinations (slug, name_en, name_de, region_en, region_de, description_en, description_de, best_time_en, best_time_de, keywords, group_key, latitude, longitude, image, placeholder, featured, position) values (${[
    q(d.slug), q(d.name.en), q(d.name.de), q(d.region.en), q(d.region.de), q(d.description.en), q(d.description.de),
    q(d.bestTime.en), q(d.bestTime.de), q(d.keywords), q(d.group), n(d.latitude), n(d.longitude), q(d.image), q(d.placeholder), b(d.featured), n(d.position),
  ].join(", ")}) on conflict (slug) do nothing;`);
}

for (const t of sample.trips) {
  out.push(`insert into public.trips (slug, title_en, title_de, summary_en, summary_de, season_en, season_de, duration_days, price_from, style, status, cover_image, placeholder, featured, position) values (${[
    q(t.slug), q(t.title.en), q(t.title.de), q(t.summary.en), q(t.summary.de), q(t.season.en), q(t.season.de),
    n(t.durationDays), n(t.priceFrom), q(t.style), q(t.status), q(t.coverImage), q(t.placeholder), b(t.featured), n(t.position),
  ].join(", ")}) on conflict (slug) do nothing;`);
  t.destinations.forEach((slug, i) =>
    out.push(`insert into public.trip_destinations (trip_id, destination_id, position) values (${tripId(t.slug)}, ${destId(slug)}, ${i}) on conflict do nothing;`));
  for (const d of t.days)
    out.push(`insert into public.trip_days (trip_id, day_number, day_label, title_en, title_de, description_en, description_de) values (${[
      tripId(t.slug), n(d.dayNumber), q(d.dayLabel), q(d.title.en), q(d.title.de), q(d.description.en), q(d.description.de),
    ].join(", ")});`);
  t.inclusions.forEach((inc, i) =>
    out.push(`insert into public.trip_inclusions (trip_id, type, text_en, text_de, position) values (${tripId(t.slug)}, ${q(inc.type)}, ${q(inc.text.en)}, ${q(inc.text.de)}, ${i});`));
  for (const o of t.offers)
    out.push(`insert into public.offers (trip_id, label_en, label_de, starts_on, ends_on, price_override, percent_off) values (${[
      tripId(t.slug), q(o.label.en), q(o.label.de), q(o.startsOn), q(o.endsOn), n(o.priceOverride), n(o.percentOff),
    ].join(", ")});`);
}

for (const r of sample.reviews) {
  out.push(`insert into public.reviews (author_name, origin_en, origin_de, trip_id, text_en, text_de, rating, status) values (${[
    q(r.authorName), q(r.origin.en), q(r.origin.de), r.tripSlug ? tripId(r.tripSlug) : "null", q(r.text.en), q(r.text.de), n(r.rating), q("hidden"),
  ].join(", ")}); -- SAMPLE review: replace with real ones`);
}

for (const p of sample.posts) {
  out.push(`insert into public.posts (slug, title_en, title_de, excerpt_en, excerpt_de, body_en, body_de, category_en, category_de, placeholder, status, published_at, meta_title_en, meta_title_de, meta_description_en, meta_description_de) values (${[
    q(p.slug), q(p.title.en), q(p.title.de), q(p.excerpt.en), q(p.excerpt.de), q(p.body.en), q(p.body.de), q(p.category.en), q(p.category.de),
    q(p.placeholder), q(p.status), q(p.publishedAt), q(p.metaTitle.en), q(p.metaTitle.de), q(p.metaDescription.en), q(p.metaDescription.de),
  ].join(", ")}) on conflict (slug) do nothing;`);
  for (const slug of p.relatedTrips)
    out.push(`insert into public.post_trips (post_id, trip_id) values ((select id from public.posts where slug = ${q(p.slug)}), ${tripId(slug)}) on conflict do nothing;`);
}

for (const s of sample.heroSlides) {
  out.push(`insert into public.hero_slides (position, is_welcome, eyebrow_en, eyebrow_de, title_en, title_de, text_en, text_de, link_label_en, link_label_de, destination_id, image, placeholder) values (${[
    n(s.position), b(s.isWelcome), q(s.eyebrow.en), q(s.eyebrow.de), q(s.title.en), q(s.title.de), q(s.text.en), q(s.text.de),
    q(s.linkLabel.en), q(s.linkLabel.de), s.destinationSlug ? destId(s.destinationSlug) : "null", q(s.image), q(s.placeholder),
  ].join(", ")});`);
}

for (const l of sample.legalPages) {
  out.push(`insert into public.legal_pages (slug, title_en, title_de, body_en, body_de) values (${[q(l.slug), q(l.title.en), q(l.title.de), q(l.body.en), q(l.body.de)].join(", ")}) on conflict (slug) do nothing;`);
}

for (const [key, value] of Object.entries(sample.settings)) {
  out.push(`insert into public.settings (key, value) values (${q(key)}, ${q(value)}) on conflict (key) do nothing;`);
}

out.push("commit;");
console.log(out.join("\n"));
